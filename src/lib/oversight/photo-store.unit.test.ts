/**
 * The upload's refusal order for the building-photo caller (DECISION-346; docs/
 * work-log/2026-11-17-congregation-profile.md, Phase 3 "Test plan", Increment 2):
 * authorization, the toggle, the type, the congregation and building, and the cap,
 * ALL before any decode; then the decode, the two private blobs, and a final
 * transaction that repeats every check with the building row locked `for update`
 * BEFORE the cap is recounted.
 *
 * No database: `withOrgContext` runs the callback against a scripted transaction
 * and every collaborator logs its call, so the ORDER is the assertion. The real
 * `preflightPhoto` and `processPhoto` run on generated bytes. The behavioural half
 * (the audit in the same transaction, the real lock, the real race) is
 * `photo-store.db.test.ts`; the source-order half is `boundaries.test.ts`.
 */
