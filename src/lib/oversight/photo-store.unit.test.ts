const h = vi.hoisted(() => {
  const state = {
    log: [] as string[],
    /** One entry per awaited `select` chain, in order. */
    script: [] as Array<{ label: string; rows: unknown[] }>,
    /** The answer to the key check; an array is consumed one answer per check. */
    held: true as boolean | boolean[],
    flag: true,
    congregation: true,
    audits: [] as Array<{ action: string; metadata: Record<string, unknown> }>,
    inserted: [] as Array<Record<string, unknown>>,
  };
  const chain = () => {
    const link: Record<string, unknown> = {};
    for (const name of ["from", "where", "limit", "orderBy"]) link[name] = () => link;
    link.for = (mode: string) => {
      state.log.push(`lock:${mode}`);
      return link;
    };
    link.then = (resolve: (rows: unknown[]) => unknown, reject: (e: unknown) => unknown) => {
      const next = state.script.shift();
      if (!next) return reject(new Error("the test script ran out of select results"));
      state.log.push(`select:${next.label}`);
      return resolve(next.rows);
    };
    return link;
  };
  const tx = {
    select: () => chain(),
    insert: () => ({
      values: (row: Record<string, unknown>) => {
        state.inserted.push(row);
        state.log.push("insert");
        return { returning: async () => [{ id: "00000000-0000-4000-8000-0000000000aa" }] };
      },
    }),
    update: () => ({
      set: () => ({
        where: async () => {
          state.log.push("update");
        },
      }),
    }),
  };
  return { state, tx };
});

