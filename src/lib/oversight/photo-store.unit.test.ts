import type { OversightCtx } from "./contract";
import { addPhoto, removePhoto, setPhotoCaption, setPhotoCover } from "./photo-store";

const ORG = "00000000-0000-4000-8000-000000000001";
const ABOUT = "00000000-0000-4000-8000-000000000002";
const BUILDING = "00000000-0000-4000-8000-000000000003";
const PHOTO = "00000000-0000-4000-8000-000000000004";
const ctx: OversightCtx = { personId: "p", organizationId: ORG, actor: { userId: "u", email: null } };

/** A small generated picture: noise, so two seeds are different bytes. */
async function jpeg(seed = 1): Promise<Buffer> {
  const raw = Buffer.alloc(64 * 48 * 3);
  let s = seed;
  for (let i = 0; i < raw.length; i += 1) {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    raw[i] = (s >> 16) & 0xff;
  }
  return sharp(raw, { raw: { width: 64, height: 48, channels: 3 } }).jpeg({ quality: 80 }).toBuffer();
}

/** A PNG signature followed by an `acTL` chunk: the animation marker the pipeline scans for. */
function animatedPng(): Buffer {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const chunk = Buffer.alloc(8 + 8 + 4);
  chunk.writeUInt32BE(8, 0);
  chunk.write("acTL", 4, "latin1");
  return Buffer.concat([signature, chunk]);
}

const script = (...entries: Array<[string, unknown[]]>) => {
  h.state.script = entries.map(([label, rows]) => ({ label, rows }));
};
const cleanFirstTransaction = (count = 3): Array<[string, unknown[]]> => [
  ["building", [{ id: BUILDING }]],
  ["count", [{ n: count }]],
];
const decoded = () => h.state.log.some((entry) => entry.startsWith("decode"));
const MANAGE = "key:congregation_oversight.manage";
const FLAG = "flag:org_portal.oversight";

beforeEach(() => {
  h.state.log = [];
  h.state.script = [];
  h.state.held = true;
  h.state.flag = true;
  h.state.congregation = true;
  h.state.audits = [];
  h.state.inserted = [];
});

describe("addPhoto: every refusal before the decode, in the design's order", () => {
  it("1. no key: forbidden, and nothing after the key check runs (not the toggle, not the congregation, not a decode)", async () => {
    h.state.held = false;
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "forbidden" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, "tx:end"]);
  });

  it("1. a bad file from a person without the key is still forbidden, not a type answer", async () => {
    h.state.held = false;
    expect(await addPhoto(ctx, ABOUT, BUILDING, Buffer.from("%PDF-1.7"))).toEqual({ kind: "refused", reason: "forbidden" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, "tx:end"]);
  });

  it("2. toggle off: not_found, after the key and before the type (a bad file is not examined)", async () => {
    h.state.flag = false;
    expect(await addPhoto(ctx, ABOUT, BUILDING, Buffer.from("%PDF-1.7"))).toEqual({ kind: "refused", reason: "not_found" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, FLAG, "tx:end"]);
  });

  it.each([
    { name: "an empty file", make: () => Buffer.alloc(0), reason: "empty" },
    { name: "a file over the upload ceiling", make: () => Buffer.alloc(1_000_001, 7), reason: "too_large" },
    { name: "a PDF", make: () => Buffer.from("%PDF-1.7 not a picture"), reason: "unsupported_type" },
    { name: "an animated PNG", make: () => animatedPng(), reason: "animated" },
  ])("3. $name is $reason, refused before the congregation or the building is looked up", async ({ make, reason }) => {
    expect(await addPhoto(ctx, ABOUT, BUILDING, make())).toEqual({ kind: "refused", reason });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, FLAG, "tx:end"]);
  });

  it("4. a congregation that is not ours: not_found, with no building read and no decode", async () => {
    h.state.congregation = false;
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "not_found" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, FLAG, "congregation", "tx:end"]);
  });

  it("4. a building that is not a live building of this congregation: not_found, no decode", async () => {
    script(["building", []]);
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "not_found" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, FLAG, "congregation", "select:building", "tx:end"]);
  });

  it("5. a building at the cap: cap_reached, and the decode never ran", async () => {
    script(...cleanFirstTransaction(10));
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "cap_reached" });
    expect(decoded()).toBe(false);
    expect(h.state.log).toEqual(["tx:begin", MANAGE, FLAG, "congregation", "select:building", "select:count", "tx:end"]);
  });

  it("the first transaction takes no row lock; only the final one does", async () => {
    script(...cleanFirstTransaction(10));
    await addPhoto(ctx, ABOUT, BUILDING, await jpeg());
    expect(h.state.log.some((entry) => entry.startsWith("lock"))).toBe(false);
  });
});

describe("addPhoto: the decode, the blobs, and the locked recheck", () => {
  it("a file that passes every cheap check and cannot be decoded is `unreadable`: the decode ran, no blob was stored, nothing was written", async () => {
    script(...cleanFirstTransaction());
    const truncated = (await jpeg()).subarray(0, 120);
    expect(await addPhoto(ctx, ABOUT, BUILDING, truncated)).toEqual({ kind: "refused", reason: "unreadable" });
    expect(h.state.log.filter((e) => e.startsWith("blob"))).toEqual([]);
    expect(h.state.inserted).toEqual([]);
    expect(h.state.audits).toEqual([]);
  });

  it("success: the whole order, a centred thumbnail, two PRIVATE blobs, a locked building row before the recount, one audit row in the same transaction", async () => {
    script(...cleanFirstTransaction(3), ["building", [{ id: BUILDING }]], ["count", [{ n: 3 }]], ["same", []], ["marked", []]);
    const result = await addPhoto(ctx, ABOUT, BUILDING, await jpeg());
    expect(result).toMatchObject({ kind: "ok", data: { cover: true } });
    expect(h.state.log).toEqual([
      // the pre-check transaction, no lock
      "tx:begin", MANAGE, FLAG, "congregation", "select:building", "select:count", "tx:end",
      // the decode (buildings crop from the centre), then the two private blobs
      "decode:centre", "blob:private", "blob:private",
      // the final transaction repeats every check, the building row locked BEFORE the recount
      "tx:begin", MANAGE, FLAG, "congregation", "lock:update", "select:building", "select:count", "select:same", "select:marked",
      "insert", "audit", "tx:end",
    ]);
    expect(h.state.inserted[0]).toMatchObject({ organizationId: ORG, aboutOrgId: ABOUT, buildingId: BUILDING, isCover: true });
    expect(h.state.audits).toHaveLength(1);
    expect(h.state.audits[0]!.action).toBe("tenant.oversight_photo.added");
    expect(Object.keys(h.state.audits[0]!.metadata).sort()).toEqual(["aboutOrgId", "buildingId", "cover", "organizationId", "photoId"]);
  });

  it("the cap is RECOUNTED under the lock: 9 live before, 10 after a competing upload, so the loser is cap_reached and writes nothing", async () => {
    script(...cleanFirstTransaction(9), ["building", [{ id: BUILDING }]], ["count", [{ n: 10 }]]);
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "cap_reached" });
    const lockAt = h.state.log.indexOf("lock:update");
    const recountAt = h.state.log.lastIndexOf("select:count");
    expect(lockAt).toBeGreaterThan(-1);
    expect(lockAt).toBeLessThan(recountAt);
    expect(h.state.inserted).toEqual([]);
    expect(h.state.audits).toEqual([]);
  });

  it("the final transaction repeats the key: a key revoked during the decode is forbidden, and nothing is written", async () => {
    script(...cleanFirstTransaction());
    h.state.held = [true, false];
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "forbidden" });
    expect(h.state.inserted).toEqual([]);
    expect(h.state.audits).toEqual([]);
  });

  it("a second live photo of the same picture is `duplicate`", async () => {
    script(...cleanFirstTransaction(), ["building", [{ id: BUILDING }]], ["count", [{ n: 3 }]], ["same", [{ id: PHOTO }]]);
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toEqual({ kind: "refused", reason: "duplicate" });
    expect(h.state.inserted).toEqual([]);
  });

  it("a building that already has a marked cover does not get a second one", async () => {
    script(...cleanFirstTransaction(), ["building", [{ id: BUILDING }]], ["count", [{ n: 3 }]], ["same", []], ["marked", [{ id: PHOTO }]]);
    expect(await addPhoto(ctx, ABOUT, BUILDING, await jpeg())).toMatchObject({ kind: "ok", data: { cover: false } });
    expect(h.state.inserted[0]).toMatchObject({ isCover: false });
  });
});

describe("the other photo writes check the key and the congregation first, and a miss writes nothing", () => {
  const calls = {
    setPhotoCaption: () => setPhotoCaption(ctx, ABOUT, BUILDING, PHOTO, "A caption"),
    setPhotoCover: () => setPhotoCover(ctx, ABOUT, BUILDING, PHOTO),
    removePhoto: () => removePhoto(ctx, ABOUT, BUILDING, PHOTO),
  };

  it.each(Object.entries(calls))("%s: no key is forbidden before anything is read", async (_name, call) => {
    h.state.held = false;
    expect(await call()).toEqual({ kind: "refused", reason: "forbidden" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, "tx:end"]);
  });

  it.each(Object.entries(calls))("%s: a congregation that is not ours is not_found before the building is read", async (_name, call) => {
    h.state.congregation = false;
    expect(await call()).toEqual({ kind: "refused", reason: "not_found" });
    expect(h.state.log).toEqual(["tx:begin", MANAGE, "congregation", "tx:end"]);
  });

  it.each(Object.entries(calls))("%s: a removed photo is `already_removed`, an unknown one `not_found`; neither writes or audits", async (_name, call) => {
    script(["building", [{ id: BUILDING }]], ["photo", [{ id: PHOTO, caption: null, isCover: false, removedAt: new Date() }]]);
    expect(await call()).toEqual({ kind: "refused", reason: "already_removed" });
    script(["building", [{ id: BUILDING }]], ["photo", []]);
    expect(await call()).toEqual({ kind: "refused", reason: "not_found" });
    expect(h.state.audits).toEqual([]);
    expect(h.state.log.includes("update")).toBe(false);
  });

  it("setPhotoCaption with the caption already stored writes and audits nothing", async () => {
    script(["building", [{ id: BUILDING }]], ["photo", [{ id: PHOTO, caption: "A caption", isCover: false, removedAt: null }]]);
    expect(await setPhotoCaption(ctx, ABOUT, BUILDING, PHOTO, "A caption")).toEqual({ kind: "ok", data: { id: PHOTO, unchanged: true } });
    expect(h.state.audits).toEqual([]);
  });

  it("setPhotoCover on the marked cover writes and audits nothing", async () => {
    script(["building", [{ id: BUILDING }]], ["photo", [{ id: PHOTO, caption: null, isCover: true, removedAt: null }]]);
    expect(await setPhotoCover(ctx, ABOUT, BUILDING, PHOTO)).toEqual({ kind: "ok", data: { id: PHOTO, unchanged: true } });
    expect(h.state.audits).toEqual([]);
  });

  it("setPhotoCover moves the mark: demote the previous, set the new, one audit row naming the previous cover", async () => {
    script(
      ["building", [{ id: BUILDING }]],
      ["photo", [{ id: PHOTO, caption: null, isCover: false, removedAt: null }]],
      ["previous", [{ id: "00000000-0000-4000-8000-0000000000bb" }]],
    );
    expect(await setPhotoCover(ctx, ABOUT, BUILDING, PHOTO)).toEqual({ kind: "ok", data: { id: PHOTO } });
    expect(h.state.log.filter((e) => e === "update")).toHaveLength(2);
    expect(h.state.audits).toHaveLength(1);
    expect(h.state.audits[0]!.metadata.previousCoverPhotoId).toBe("00000000-0000-4000-8000-0000000000bb");
  });

  it("removePhoto and setPhotoCaption take the building row lock first (they serialize with an upload)", async () => {
    script(["building", [{ id: BUILDING }]], ["photo", [{ id: PHOTO, caption: null, isCover: false, removedAt: null }]]);
    await removePhoto(ctx, ABOUT, BUILDING, PHOTO);
    expect(h.state.log.indexOf("lock:update")).toBeLessThan(h.state.log.indexOf("select:building"));
    expect(h.state.audits[0]!.action).toBe("tenant.oversight_photo.removed");
  });
});
